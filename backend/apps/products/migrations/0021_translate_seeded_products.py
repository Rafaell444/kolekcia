def translate_seeded_products(apps, schema_editor):
    Product = apps.get_model("products", "Product")
    for slug, translations in TRANSLATIONS.items():
        product = Product.objects.filter(slug=slug).first()
        if not product:
            continue

        changed = []
        for language, (title, description) in translations.items():
            title_field = f"title_{language}"
            description_field = f"description_{language}"
            if not getattr(product, title_field) or getattr(product, title_field) == product.title:
                setattr(product, title_field, title)
                changed.append(title_field)
            if not getattr(product, description_field) or getattr(product, description_field) == product.description:
                setattr(product, description_field, description)
                changed.append(description_field)
        if changed:
            product.save(update_fields=changed)


