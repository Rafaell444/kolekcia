def deep_merge(base, translated):
    if isinstance(base, dict) and isinstance(translated, dict):
        result = dict(base)
        for key, value in translated.items():
            result[key] = deep_merge(result.get(key), value)
        return result
    if isinstance(base, list) and isinstance(translated, list):
        result = list(base)
        for index, value in enumerate(translated):
            if index < len(result):
                result[index] = deep_merge(result[index], value)
            else:
                result.append(value)
        return result
    return translated


